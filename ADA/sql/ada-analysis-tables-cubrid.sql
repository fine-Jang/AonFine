-- Shared second step for BOTH fresh install and existing DUMP_TYPE/HOST_NM installations.
-- No automatic execution by the application. No Worker process/queue is started.
-- Run only after TB_ADA_DUMP exists. Do not rerun on an already migrated schema.
-- State membership/transitions are validated by application/CAS contract, not CHECK:
-- CUBRID manuals document CHECK as parsed but ignored in some versions.

CREATE TABLE TB_ADA_ANALYSIS_JOB (
    JOB_ID VARCHAR(36) NOT NULL,
    DUMP_ID VARCHAR(36) NOT NULL,
    CURRENT_ATTEMPT_ID VARCHAR(36),
    STATUS_CD VARCHAR(20) DEFAULT 'IDLE' NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    REQUESTED_BY VARCHAR(50) NOT NULL,
    REG_DT DATETIME DEFAULT CURRENT_DATETIME NOT NULL,
    MOD_DT DATETIME,
    CONSTRAINT PK_ADA_ANALYSIS_JOB PRIMARY KEY (JOB_ID),
    CONSTRAINT UX_ADA_ANALYSIS_DUMP UNIQUE (DUMP_ID),
    CONSTRAINT FK_ADA_JOB_DUMP FOREIGN KEY (DUMP_ID) REFERENCES TB_ADA_DUMP (DUMP_ID)
);

CREATE TABLE TB_ADA_ANALYSIS_ATTEMPT (
    JOB_ID VARCHAR(36) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    ATTEMPT_NO INTEGER NOT NULL,
    REQUEST_KEY VARCHAR(36) NOT NULL,
    STATUS_CD VARCHAR(20) DEFAULT 'QUEUED' NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CANCEL_REQUESTED_YN CHAR(1) DEFAULT 'N' NOT NULL,
    CANCEL_REQUESTED_BY VARCHAR(50),
    CANCEL_REQUESTED_DT DATETIME,
    REQUESTED_BY VARCHAR(50) NOT NULL,
    WORKER_ID VARCHAR(100),
    START_DT DATETIME,
    END_DT DATETIME,
    LAST_HEARTBEAT_DT DATETIME,
    FAIL_CODE VARCHAR(50),
    FAIL_REASON VARCHAR(1000),
    RESULT_PATH VARCHAR(1000),
    REG_DT DATETIME DEFAULT CURRENT_DATETIME NOT NULL,
    MOD_DT DATETIME,
    CONSTRAINT PK_ADA_ANALYSIS_ATTEMPT PRIMARY KEY (JOB_ID, ATTEMPT_ID),
    CONSTRAINT UX_ADA_ATTEMPT_ID UNIQUE (ATTEMPT_ID),
    CONSTRAINT UX_ADA_ATTEMPT_NO UNIQUE (JOB_ID, ATTEMPT_NO),
    CONSTRAINT UX_ADA_ATTEMPT_REQUEST UNIQUE (REQUEST_KEY),
    CONSTRAINT FK_ADA_ATTEMPT_JOB FOREIGN KEY (JOB_ID) REFERENCES TB_ADA_ANALYSIS_JOB (JOB_ID)
);

-- Composite FK prevents CURRENT_ATTEMPT_ID from pointing at a different job's attempt.
ALTER TABLE TB_ADA_ANALYSIS_JOB ADD CONSTRAINT FK_ADA_JOB_CURRENT
    FOREIGN KEY (JOB_ID, CURRENT_ATTEMPT_ID)
    REFERENCES TB_ADA_ANALYSIS_ATTEMPT (JOB_ID, ATTEMPT_ID);

CREATE INDEX IX_ADA_JOB_STATUS ON TB_ADA_ANALYSIS_JOB (STATUS_CD, MOD_DT);
CREATE INDEX IX_ADA_ATTEMPT_HEARTBEAT ON TB_ADA_ANALYSIS_ATTEMPT (STATUS_CD, LAST_HEARTBEAT_DT);

-- JOB states: IDLE (no attempt), QUEUED, RUNNING, CANCEL_REQUESTED,
--             CANCELLED, FAILED, SUCCEEDED, RECOVERY_REQUIRED.
-- ATTEMPT states: same except IDLE. No attempt is created during this preparation release.
-- Timestamps/worker/failure/result are owned by each attempt. JOB status is its current snapshot.
-- REQUEST_KEY is client idempotency UUID; retry uses a NEW request key and NEW attempt ID.
